import { spawn } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "../../../../..");
const scriptPath = path.join(__dirname, "griffe_generate.py");
const contentDir = path.join(repoRoot, "apps", "docs", "src", "content", "_autogenerated");
const targets = [
	path.join(repoRoot, "apps", "gui", "src"),
	path.join(repoRoot, "packages", "core", "src"),
	path.join(repoRoot, "packages", "utils", "src"),
];

function run(cmd: string, args: string[]): Promise<void> {
	return new Promise((resolve, reject) => {
		const child = spawn(cmd, args, { stdio: "inherit" });
		child.on("error", reject);
		child.on("close", (code) => {
			if (code === 0) resolve();
			else reject(new Error(`Command failed (${code}): ${cmd} ${args.join(" ")}`));
		});
	});
}

export async function generateGriffe(): Promise<void> {
	for (const target of targets) {
		await run("python", [scriptPath, target, "--output", contentDir]);
	}
}
