import { spawn } from "node:child_process";
import { rmdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "../../../../..");
const scriptPath = path.join(__dirname, "griffe_generate.py");
const contentDir = path.join(repoRoot, "apps", "docs", "src", "content", "_autogenerated");

const workspaces = [
	["apps", "gui"],
	["apps", "cli"],
	["packages", "utils"],
	["packages", "rpc"],
	["packages", "backend"],
	["packages", "benchmark"],
];

function run(cmd: string, args: string[]): Promise<void> {
	return new Promise((resolve, reject) => {
		const child = spawn(cmd, args, { stdio: "inherit" });
		child.on("error", reject);
		child.on("close", (code) => {
			if (code === 0) resolve();
			else reject(new Error(`Command failed (${code}): ${cmd} ${args.join(" ")}`));
		});
	});
}

export async function generateGriffe(): Promise<void> {
	try {
		rmdirSync(contentDir, { recursive: true });
	} catch (_e) {
		/* ignore */
	}
	const targets = workspaces.map(([scope, name]) => [
		`${scope}.${name}`,
		path.join(repoRoot, scope, name, "src"),
	]);

	const tasks = targets.map(([targetName, targetPath]) =>
		run("python", [scriptPath, targetPath, "--output", path.join(contentDir, targetName)]),
	);

	await Promise.all(tasks);
}
